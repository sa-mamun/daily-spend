const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const filename = path.resolve('src/features/reports/categoryDonut.ts');
const moduleResult = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS }
}).outputText, { module: moduleResult, exports: moduleResult.exports, Map, Number, Math });
const { categoryDonut, donutArc } = moduleResult.exports;
const expense = (categoryId, amount, categoryName = 'Category ' + categoryId) => ({ categoryId, amount, categoryName });
assert.equal(categoryDonut([]).total, 0);
assert.equal(categoryDonut([]).slices.length, 0);
const single = categoryDonut([expense(1, 125), expense(1, 75)]);
assert.equal(single.total, 200);
assert.equal(single.slices.length, 1);
assert.equal(single.slices[0].percentage, 100);
assert.ok(!donutArc(0,360).includes('NaN'));
assert.equal((donutArc(0,360).match(/A62,62/g)||[]).length, 2);
const many = categoryDonut([7,6,5,4,3,2,1].map((amount, index) => expense(index, amount)));
assert.equal(many.total, 28);
assert.equal(many.slices.length, 5);
assert.equal(many.slices[4].key, 'others');
assert.equal(many.slices[4].amount, 6);
assert.equal(many.slices[4].categoryIds.length, 3);
assert.equal(many.slices.reduce((sum,slice)=>sum+slice.amount,0), many.total);
assert.equal(many.slices.reduce((sum,slice)=>sum+slice.percentage,0),100);
const equal = categoryDonut([expense(1,1),expense(2,1),expense(3,1)]);
assert.equal(equal.slices.reduce((sum,slice)=>sum+slice.percentage,0),100);
assert.equal(categoryDonut([expense(1,10,'Same'),expense(2,20,'Same')]).slices.length,2);
assert.equal(categoryDonut([expense(1,-1),expense(2,NaN),expense(3,Infinity)]).total,0);
assert.ok(!donutArc(90,90.01).includes('NaN'));
const component = fs.readFileSync('src/features/reports/CategoryDonutChart.tsx','utf8');
assert.ok(component.includes('expense.categoryId !== selectedId'));
assert.ok(component.includes('subcategoryId ?? "general"'));
assert.ok(component.includes('onPress={() => select(slice.key)}'));
assert.ok(component.includes('accessibilityState={{ expanded:'));
assert.ok(component.includes('mintTheme(dark)'));
assert.ok(component.includes('"By subcategory" : "সাব-ক্যাটাগরি অনুযায়ী"'));
const screen = fs.readFileSync('src/features/reports/ReportsScreen.tsx','utf8');
assert.ok(screen.includes('<CategoryDonutChart key={periodLabel} expenses={periodExpenses} />'));
assert.ok(!screen.includes('.slice(0, 5)'));
console.log('PASS: empty, single/full circle, all-category totals, Others drilldown, duplicate names, rounding, invalid amounts, period reset and theme/language integration');
